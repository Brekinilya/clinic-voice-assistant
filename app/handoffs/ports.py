"""Ports для хранилища заявок; сеть МИС сюда не входит."""

from datetime import datetime
from typing import Protocol

from app.handoffs.models import (
    CallbackAttempt,
    CallbackDraft,
    CallbackTask,
    HandoffRequest,
    MisOperation,
    TransferAttempt,
    TransferState,
)


class HandoffConflict(Exception):
    """Версия устарела либо повторный идентификатор получил другое содержимое."""


class HandoffStore(Protocol):
    async def create_request(self, request: HandoffRequest) -> HandoffRequest: ...
    async def get_request(self, request_id: str) -> HandoffRequest | None: ...
    async def request_for_call(self, call_id: str) -> HandoffRequest | None: ...
    async def list_requests(self, *, limit: int, offset: int, state: str | None = None): ...
    async def begin_attempt(self, attempt: TransferAttempt) -> TransferAttempt: ...
    async def finish_attempt(
        self, attempt_id: str, outcome: TransferState, finished_at: datetime, reason: str | None,
        *, call_id: str, route: str | None, priority: str, operation: MisOperation | None = None
    ) -> tuple[HandoffRequest, TransferAttempt]: ...
    async def save_request(self, request: HandoffRequest, *, expected_version: int): ...
    async def create_mis_operation(self, operation: MisOperation): ...
    async def get_mis_operation(self, operation_id: str): ...
    async def update_mis_operation(self, operation: MisOperation, *, expected_version: int): ...
    async def due_mis_operations(self, now: datetime, limit: int): ...
    async def save_callback_draft(
        self, draft: CallbackDraft, *, expected_version: int | None
    ): ...
    async def get_callback_draft(self, request_id: str): ...
    async def advance_callback_input(self, call_id: str, turn_id: int): ...
    async def revoke_callback_draft(self, call_id: str): ...
    async def delete_callback_draft(
        self, request_id: str, *, expected_version: int | None = None
    ): ...
    async def create_callback_task(
        self, task: CallbackTask, *, draft_version: int,
        consent_turn_id: int, input_epoch: int
    ): ...
    async def get_callback_task(self, task_id: str): ...
    async def get_callback_task_by_request(self, request_id: str): ...
    async def list_callback_tasks(self, *, limit: int, offset: int, state: str | None = None): ...
    async def claim_callback_task(
        self, task_id: str, owner: str, expected_version: int, now: datetime, lease_until: datetime
    ): ...
    async def start_callback_attempt(
        self, attempt: CallbackAttempt, *, expected_version: int, now: datetime
    ): ...
    async def finish_callback_attempt(
        self, attempt_id: str, outcome: str, finished_at: datetime, reason: str | None,
        *, owner: str, expected_version: int
    ): ...
    async def cancel_callback_task(
        self, task_id: str, owner: str, expected_version: int, now: datetime
    ): ...
    async def callback_attempts_for_task(self, task_id: str): ...
    async def get_callback_attempt(self, attempt_id: str): ...
    async def recover_callback_tasks(self, now: datetime): ...
