"""Границы сбоев голосового шлюза: где ошибку чужого компонента гасим, чтобы не уронить звонок.

Общий перехват Exception в app/voice допустим только на границе с компонентом, который шлюз не
контролирует: диалог, синтез, распознавание, ARI, получатель исхода. Сбой там не должен оборвать
разговор: шлюз закрывается безопасно — переспрашивает, переводит или кладёт трубку. Каждый такой
перехват пишет в журнал через failure() одной строкой: код события, номер звонка, тип исключения.

Текст исключения в журнал не попадает: в нём может оказаться реплика пациента или ответ МИС
(152-ФЗ). Трассировка — только для инфраструктуры без текстов разговора (ARI, RTP, журнал перевода)
и на уровне DEBUG. Ожидаемые сбои (таймауты) перехватываются отдельно и получают свой код.
Тест tests/voice/test_failures.py не даёт добавить общий перехват без failure().
"""

import logging

log = logging.getLogger("app.voice.failures")


def failure(event: str, error: BaseException, *, call: str | None = None, trace=False) -> None:
    """Сбой на границе: код события вида voice.<что>_failed, номер звонка, тип исключения."""
    detailed = trace or log.isEnabledFor(logging.DEBUG)
    log.error(
        "%s звонок=%s ошибка=%s",
        event,
        call or "-",
        type(error).__name__,
        exc_info=error if detailed else None,
    )
