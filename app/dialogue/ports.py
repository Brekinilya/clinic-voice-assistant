"""Короткие атомарные операции; обработка команды выполняется без открытой транзакции."""

from typing import Protocol

from app.contracts import NluResult, SafetyDecision
from app.dialogue.models import Claim, DialogueState, Reply, TransferRequest, Turn


class DialogueStore(Protocol):
    async def inspect(self, call_id: str) -> DialogueState: ...
    async def claim(self, call_id: str, turn_id: int, digest: str) -> Claim: ...
    async def complete(self, state: DialogueState, turn_id: int, result: Reply) -> bool: ...
    async def end(self, call_id: str) -> DialogueState: ...
    async def observe(self, call_id: str, turn_id: int, digest: str) -> DialogueState: ...
    async def authorize(self, call_id: str, version: int, epoch: int, turn_id: int) -> bool: ...
    async def preempt(
        self, call_id: str, turn_id: int, transfer: TransferRequest
    ) -> DialogueState: ...


class SafetyChecker(Protocol):
    def evaluate(self, call_id: str, turn: Turn, extra=frozenset()) -> SafetyDecision: ...


class NluInterpreter(Protocol):
    async def parse(self, state: DialogueState, turn: Turn) -> NluResult: ...


class Conversation(Protocol):
    async def release_call(self, call_id: str) -> None: ...
    async def short_reply(
        self, state: DialogueState, turn: Turn
    ) -> tuple[DialogueState, Reply] | None: ...
    async def step(self, state: DialogueState, turn: Turn) -> tuple[DialogueState, Reply]: ...
