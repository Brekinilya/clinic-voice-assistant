"""Границы напоминаний: хранилище заданий, исходящий вызов. Порт диалога — app/dialogue/outbound."""

from datetime import date, datetime, timedelta
from typing import Literal, Protocol

from app.dialogue.outbound import OutboundContext
from app.outbox.models import OutboxJob
from app.reminders.models import Contact, ReminderAttempt, ReminderJob, ReminderMark


class DialRejected(Exception):
    """Вызов не начался: шлюз отклонил originate. Звонка точно не было."""


class ReminderStore(Protocol):
    """Каждый метод — одна атомарная операция. Попытку меняет только владелец lease."""

    async def planned(self, call_day: date) -> bool: ...
    async def mark_planned(self, call_day: date) -> None: ...
    async def add_job(self, job: ReminderJob, now: datetime | None = None) -> bool: ...
    async def job(self, job_id: str) -> ReminderJob: ...
    async def attempt(self, attempt_id: str) -> ReminderAttempt: ...
    async def due(self, now: datetime, limit: int) -> list[ReminderJob]: ...
    async def list_jobs(
        self, call_day: date | None = None, state: str | None = None, limit: int = 50
    ) -> list[ReminderJob]: ...
    async def claim(
        self, job_id: str, owner: str, now: datetime, lease: timedelta
    ) -> ReminderAttempt | None: ...
    async def advance(
        self,
        attempt_id: str,
        owner: str,
        state: Literal["dialing", "answered"] | None,
        now: datetime,
        lease: timedelta,
    ) -> ReminderAttempt: ...
    async def guard(self, attempt_id: str, fence: int, now: datetime) -> bool:
        """Попытка всё ещё действует и fence совпадает: иначе контекст звонка устарел."""
        ...

    async def finish(
        self,
        attempt_id: str,
        result: str,
        reason: str | None,
        now: datetime,
        job: dict,
        mis_status: str | None = None,
    ) -> bool: ...
    async def outbox_events(self, source_id: str) -> tuple[OutboxJob, ...]: ...
    async def stale(self, now: datetime) -> list[ReminderAttempt]: ...
    async def recover(self, attempt_id: str, now: datetime) -> None: ...
    async def contact(self, client_id: int) -> Contact | None: ...
    async def save_contact(self, contact: Contact) -> None: ...
    async def opt_out(self, client_id: int, now: datetime) -> None: ...
    async def opt_out_all(self, client_id: int, now: datetime) -> None: ...
    async def confirmed(self, visit_id: int, scheduled_at=None, doctor_id=None) -> bool: ...
    async def mark_confirmed(
        self, visit_id: int, now: datetime, scheduled_at=None, doctor_id=None
    ) -> None: ...
    async def prepare_mark(self, mark: ReminderMark) -> ReminderMark: ...
    async def mark(self, mark_id: str) -> ReminderMark | None: ...
    async def start_mark(self, mark_id, context, now, owner, approval=None) -> ReminderMark | None:
        """Атомарно сверить диалог/попытку/блокировку и перевести prepared в sending."""
        ...

    async def move_mark(
        self, mark_id: str, expected: set[str], **changes
    ) -> ReminderMark | None: ...
    async def marks_to_check(self, now: datetime) -> list[ReminderMark]: ...
    async def lock_client(
        self, client_id: int, owner: str, now: datetime, ttl: timedelta
    ) -> bool: ...
    async def unlock_client(self, client_id: int, owner: str) -> None: ...


class Dialer(Protocol):
    async def call_out(
        self, attempt_id: str, endpoint: str, context: OutboundContext, channel_id: str
    ) -> None:
        """Отдать вызов шлюзу. Исход придёт позже через ReminderExecutor.finished."""
        ...
